export function searchPageMap(query: string): PageAnchor[] {
  const q = query.toLowerCase();
  const scored = SMETOPLAN_PAGE_MAP.map((a) => {
    let score = 0;
    for (const k of a.keywords) {
      if (q.includes(k)) score += 2;
    }
    if (q.includes(a.title.toLowerCase())) score += 3;
    if (q.includes(a.id)) score += 4;
    return { a, score };
  })
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score);
  return scored.slice(0, 4).map((x) => x.a);
}

